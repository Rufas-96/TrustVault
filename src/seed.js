// Builds a small, valid one-page PDF containing the given lines of ASCII text.
function simplePdf(lines) {
  const esc = (s) => s.replace(/[\\()]/g, (c) => `\\${c}`);
  const stream = ['BT', '/F1 12 Tf', '72 740 Td', '18 TL', ...lines.map((l) => `(${esc(l)}) Tj T*`), 'ET'].join('\n');
  const objects = [
    '<< /Type /Catalog /Pages 2 0 R >>',
    '<< /Type /Pages /Kids [3 0 R] /Count 1 >>',
    '<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Contents 4 0 R /Resources << /Font << /F1 5 0 R >> >> >>',
    `<< /Length ${Buffer.byteLength(stream, 'latin1')} >>\nstream\n${stream}\nendstream`,
    '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>',
  ];
  let out = '%PDF-1.4\n';
  const offsets = [];
  objects.forEach((body, i) => {
    offsets.push(Buffer.byteLength(out, 'latin1'));
    out += `${i + 1} 0 obj\n${body}\nendobj\n`;
  });
  const xref = Buffer.byteLength(out, 'latin1');
  out += `xref\n0 ${objects.length + 1}\n0000000000 65535 f \n`;
  out += offsets.map((o) => `${String(o).padStart(10, '0')} 00000 n \n`).join('');
  out += `trailer\n<< /Size ${objects.length + 1} /Root 1 0 R >>\nstartxref\n${xref}\n%%EOF\n`;
  return Buffer.from(out, 'latin1');
}

const pdf = (name, lines) => ({ buffer: simplePdf(lines), name, extension: 'pdf', mime: 'application/pdf' });
const txt = (name, body, ext = 'txt') => ({
  buffer: Buffer.from(body, 'utf8'), name, extension: ext, mime: ext === 'csv' ? 'text/csv; charset=utf-8' : 'text/plain; charset=utf-8',
});

async function seedDemoData(ctx) {
  const { db, audit } = ctx;
  if (db.prepare('SELECT COUNT(*) AS n FROM users').get().n > 0) return false;

  const u = {};
  for (const spec of DEMO_USERS) u[spec.key] = await createUser(db, spec);
  audit.record({ actor: null, action: 'system.seed', details: { users: DEMO_USERS.map((x) => x.username), note: 'Demo data. Entries marked demo:true were generated by the seed script, not by real people.' } });

  const doc = (owner, title, description, category, file) =>
    createDocument(ctx, { req: null, owner, title, description, category, file });
  const getDoc = (id) => db.prepare('SELECT * FROM documents WHERE id = ?').get(id);

  // ---- HR (Alice) --------------------------------------------------------------------------
  const salary = doc(u.alice, 'Salary letter - Carol Diaz 2026', 'Annual compensation letter. Confidential to the employee and HR.', 'HR',
    pdf('salary-letter-carol-diaz-2026.pdf', ['Contoso Ltd - Human Resources', '', 'Salary letter - Carol Diaz', 'Effective 1 April 2026', 'Annual gross: INR 9,60,000', '', 'Confidential: HR and the named employee only.']));
  const handbook = doc(u.alice, 'Employee Handbook 2026', 'Policies for all employees: leave, conduct, information security.', 'HR',
    txt('employee-handbook-2026.txt', 'CONTOSO EMPLOYEE HANDBOOK 2026\n\n1. Leave policy\n2. Code of conduct\n3. Information security: never share documents outside TrustVault.\n4. Reporting a leak: contact security@contoso.example\n'));
  const payroll = doc(u.alice, 'Payroll summary Q3 2026', 'Quarterly payroll totals by department. HR only.', 'Finance',
    txt('payroll-q3-2026.csv', 'department,headcount,total_inr\nEngineering,42,1.92 Cr\nSales,18,0.71 Cr\nHR,6,0.22 Cr\nFinance,8,0.34 Cr\n', 'csv'));
  const offer = doc(u.alice, 'Offer letter template', 'Standard offer letter used for new hires.', 'HR',
    txt('offer-letter-template.txt', 'Dear [Candidate],\n\nWe are pleased to offer you the position of [Role] at Contoso Ltd...\n'));

  // ---- Legal (Bob) -------------------------------------------------------------------------
  const msa = doc(u.bob, 'Master Services Agreement - Northwind', 'Contract under negotiation with Northwind Traders.', 'Legal',
    pdf('msa-northwind-draft.pdf', ['Master Services Agreement', 'Between Contoso Ltd and Northwind Traders', '', 'DRAFT v1 - for negotiation', 'Clause 7: Liability is capped at fees paid.']));
  const minutes = doc(u.bob, 'Board minutes - September 2026', 'Minutes of the September board meeting. Restricted.', 'Legal',
    pdf('board-minutes-2026-09.pdf', ['Board minutes - September 2026', '', 'Item 1: Approval of FY27 budget', 'Item 2: Acquisition discussion (restricted)']));
  const drawing = doc(u.bob, 'Site drawing - Building C', 'Layout drawing shared with the external contractor.', 'Engineering',
    txt('building-c-layout.txt', 'BUILDING C - FLOOR PLAN NOTES\nGrid A-F, levels 0-3. Fire exits at A1, F3.\nService riser at C2.\n'));
  const pricing = doc(u.bob, 'Pricing proposal - Northwind', 'Commercial proposal sent during negotiation.', 'Sales',
    txt('pricing-proposal-northwind.txt', 'Pricing proposal for Northwind Traders\nTier A: INR 12 L / year\nTier B: INR 18 L / year\n'));
  const oldNda = doc(u.bob, 'NDA - Fabrikam (expired)', 'Old NDA kept for reference, superseded in 2025.', 'Legal',
    txt('nda-fabrikam-2023.txt', 'Mutual NDA between Contoso Ltd and Fabrikam Inc. Term: 2023-2025.\n'));

  // ---- Finance (Raj) -----------------------------------------------------------------------
  const auditQ2 = doc(u.raj, 'Audit papers - FY26 Q2', 'Working papers for the external statutory audit.', 'Audit',
    txt('audit-papers-fy26-q2.csv', 'account,opening,closing,variance\nCash,4.2 Cr,4.6 Cr,+0.4 Cr\nReceivables,2.1 Cr,2.5 Cr,+0.4 Cr\nPayables,1.8 Cr,1.7 Cr,-0.1 Cr\n', 'csv'));
  const vendors = doc(u.raj, 'Vendor payment register', 'All vendor payments this financial year. Finance only.', 'Finance',
    txt('vendor-payments-fy26.csv', 'vendor,invoice,amount_inr,status\nNorthwind Traders,INV-2291,8,40,000,paid\nFabrikam Inc,INV-0612,2,15,000,pending\n', 'csv'));
  const budget = doc(u.raj, 'FY27 budget draft', 'Draft budget for board approval.', 'Finance',
    pdf('fy27-budget-draft.pdf', ['FY27 Budget - DRAFT', '', 'Revenue target: INR 42 Cr', 'Opex: INR 31 Cr', 'For board review only.']));

  // ---- Grants --------------------------------------------------------------------------------
  const grant = (owner, documentId, grantee, level, expiresAt = null) => transaction(db, () => {
    db.prepare('INSERT INTO permissions (document_id, user_id, level, granted_by, granted_at, expires_at) VALUES (?, ?, ?, ?, ?, ?)')
      .run(documentId, grantee.id, level, owner.id, Date.now(), expiresAt);
    audit.record({ actor: owner, action: 'permission.grant', documentId, targetUserId: grantee.id, details: { title: getDoc(documentId).title, grantee: grantee.username, level, expiresAt } });
  });
  grant(u.alice, salary, u.carol, 'read');
  grant(u.alice, handbook, u.carol, 'read');
  grant(u.alice, handbook, u.dave, 'read');
  grant(u.bob, msa, u.dave, 'edit');
  grant(u.bob, drawing, u.dave, 'read', Date.now() + 7 * DAY);
  grant(u.raj, auditQ2, u.priya, 'read', Date.now() + 30 * DAY);
  grant(u.raj, budget, u.bob, 'read');
  // A grant that has already run out: shows that expiry needs no clean-up job.
  grant(u.bob, pricing, u.dave, 'read', Date.now() + DAY);
  db.prepare('UPDATE permissions SET expires_at = ? WHERE document_id = ? AND user_id = ?').run(Date.now() - DAY, pricing, u.dave.id);

  // ---- Versions, trash -----------------------------------------------------------------------
  addVersion(ctx, { req: null, doc: getDoc(msa), user: u.dave, file: pdf('msa-northwind-redline.pdf', ['Master Services Agreement', 'Between Contoso Ltd and Northwind Traders', '', 'DRAFT v2 - Northwind redline', 'Clause 7: Liability capped at 2x fees paid (proposed).']) });
  addVersion(ctx, { req: null, doc: getDoc(salary), user: u.alice, file: pdf('salary-letter-carol-diaz-2026-v2.pdf', ['Contoso Ltd - Human Resources', '', 'Salary letter - Carol Diaz (revised)', 'Effective 1 April 2026', 'Annual gross: INR 10,08,000', '', 'Confidential: HR and the named employee only.']) });
  transaction(db, () => {
    db.prepare('UPDATE documents SET deleted_at = ?, deleted_by = ? WHERE id = ?').run(Date.now(), u.bob.id, oldNda);
    audit.record({ actor: u.bob, action: 'document.delete', documentId: oldNda, details: { title: getDoc(oldNda).title } });
  });

  // ---- A little activity so the dashboards and alerts are not empty. --------------------------
  // These entries are flagged demo:true so nobody mistakes them for real behaviour.
  const ev = (actor, action, documentId, outcome = 'success', extra = {}) =>
    audit.record({ actor, action, documentId, outcome, details: { title: documentId ? getDoc(documentId).title : undefined, demo: true, ...extra } });
  ev(u.carol, 'document.view', salary);
  ev(u.carol, 'document.download', salary, 'success', { version: 2 });
  ev(u.dave, 'document.download', msa, 'success', { version: 1 });
  ev(u.priya, 'document.view', auditQ2);
  ev(u.priya, 'document.download', auditQ2, 'success', { version: 1 });
  for (let i = 0; i < 3; i += 1) ev(u.carol, 'document.download', payroll, 'denied', { reason: 'no_access' });
  ev(u.dave, 'document.view', minutes, 'denied', { reason: 'no_access' });
  ev(u.dave, 'document.download', pricing, 'denied', { reason: 'no_access', note: 'grant expired' });
  for (let i = 0; i < 3; i += 1) audit.record({ actor: null, action: 'auth.login', outcome: 'denied', details: { username: 'raj', reason: 'wrong_password', demo: true } });

  void offer; void vendors; // shared with nobody: good targets for access tests
  return true;
}

